-- order_lines keeps its business key (order_no, line_no) as UNIQUE and gains a generated
-- surrogate key, line_id, because Django's admin and forms need a single-column primary key.
-- Run once, in the Neon SQL Editor, on your scarlet database. Safe to re-run? No: run it once.
ALTER TABLE order_lines ADD COLUMN line_id INTEGER GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE order_lines DROP CONSTRAINT order_lines_pkey;
ALTER TABLE order_lines ADD PRIMARY KEY (line_id);
ALTER TABLE order_lines ADD CONSTRAINT order_lines_order_no_line_no_key UNIQUE (order_no, line_no);
